/*
 * Builds the site into dist/: two classic scripts (IIFE, not modules, so that dist/index.html also works when
 * opened from disk, file://), plus index.html, css/, LICENSE and the licences of the bundled libraries.
 * js/site.js holds the site and data/*.json; js/media-graph.js holds Cytoscape and the media drawings, added by
 * the media page on first use (PRD-0001 §8 graph libraries).
 *
 *   node tools/build.ts      (npm run build)
 */
import { cpSync, mkdirSync, readFileSync, rmSync, statSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { build, type Plugin } from "esbuild";
import { parseForSite } from "./maintainer-fields.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIST = join(ROOT, "dist");

rmSync(DIST, { recursive: true, force: true });

/** Removes the maintainer-only fields of data/*.json from the bundle (tools/maintainer-fields.ts). */
const stripMaintainerFields: Plugin = {
  name: "strip-maintainer-fields",
  setup(b) {
    b.onLoad({ filter: /[\\/]data[\\/][^\\/]+\.json$/ }, (args) => {
      const json = parseForSite(readFileSync(args.path, "utf8"));
      return { contents: JSON.stringify(json), loader: "json" };
    });
  },
};

/** The runtime libraries bundled into js/media-graph.js, whose licences are copied to dist/licenses/. */
const BUNDLED_LIBRARIES = ["cytoscape", "cytoscape-fcose", "cose-base", "layout-base"];

const SCRIPTS = [
  { entry: "src/site/main.ts", out: "js/site.js", minify: false },
  // Minified: the libraries make most of it, and a phone downloads it on first opening of the graph.
  { entry: "src/site/media-graph.ts", out: "js/media-graph.js", minify: true },
];

for (const s of SCRIPTS) {
  await build({
    entryPoints: [join(ROOT, s.entry)],
    outfile: join(DIST, s.out),
    bundle: true,
    format: "iife",
    platform: "browser",
    target: ["es2020"],
    charset: "utf8",
    minify: s.minify,
    banner: { js: "/* Boussole citoyenne. Generated by `npm run build` from src/site and data/: do not edit. */" },
    logLevel: "warning",
    plugins: [stripMaintainerFields],
  });
}

for (const path of ["index.html", "css", "LICENSE"]) {
  cpSync(join(ROOT, path), join(DIST, path), { recursive: true });
}
mkdirSync(join(DIST, "licenses"));
for (const lib of BUNDLED_LIBRARIES) {
  cpSync(join(ROOT, "node_modules", lib, "LICENSE"), join(DIST, "licenses", lib + ".txt"));
}

const sizes = SCRIPTS.map((s) => `${s.out} (${Math.round(statSync(join(DIST, s.out)).size / 1024)} Ko)`);
console.log(`Site construit dans ${relative(ROOT, DIST)}/ : ${sizes.join(", ")}, index.html, css/, LICENSE, licenses/.`);
