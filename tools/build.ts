/*
 * Builds the site into dist/: one classic script (IIFE, not a module, so that dist/index.html
 * also works when opened from disk, file://) with data/*.json inside, plus index.html, css/ and LICENSE.
 *
 *   node tools/build.ts      (npm run build)
 */
import { cpSync, readFileSync, rmSync, statSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { build, type Plugin } from "esbuild";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIST = join(ROOT, "dist");

rmSync(DIST, { recursive: true, force: true });

/** Fields of data/*.json kept for the maintainers only: removed from the bundle, the site never reads them. */
const MAINTAINER_ONLY = new Set(["_readme", "left_right"]);
const stripMaintainerFields: Plugin = {
  name: "strip-maintainer-fields",
  setup(b) {
    b.onLoad({ filter: /[\\/]data[\\/][^\\/]+\.json$/ }, (args) => {
      const json = JSON.parse(readFileSync(args.path, "utf8"), (key, value) => (MAINTAINER_ONLY.has(key) ? undefined : value));
      return { contents: JSON.stringify(json), loader: "json" };
    });
  },
};

await build({
  entryPoints: [join(ROOT, "src/site/main.ts")],
  outfile: join(DIST, "js/site.js"),
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["es2020"],
  charset: "utf8",
  banner: { js: "/* Boussole citoyenne. Generated by `npm run build` from src/site and data/: do not edit. */" },
  logLevel: "warning",
  plugins: [stripMaintainerFields],
});

for (const path of ["index.html", "css", "LICENSE"]) {
  cpSync(join(ROOT, path), join(DIST, path), { recursive: true });
}

const script = join(DIST, "js/site.js");
console.log(`Site construit dans ${relative(ROOT, DIST)}/ : ${relative(ROOT, script)} (${Math.round(statSync(script).size / 1024)} Ko), index.html, css/, LICENSE.`);
