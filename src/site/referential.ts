/*
 * The referential as the site sees it. data/*.json is bundled into the script at build time
 * (no fetch: the site must work when index.html is opened from disk).
 *
 * Voters only ever see verified links (PRD-0001 §8): the link status is internal to the maintainer.
 * A state site or a tool whose link is not verified is left out of the lists; a party stays, but
 * its URL is hidden and its card offers a search instead.
 */
import territoriesFile from "../../data/territories.json";
import partiesFile from "../../data/parties.json";
import stateSitesFile from "../../data/state-sites.json";
import toolsFile from "../../data/tools.json";
import ballotFile from "../../data/ballot.json";
import parliamentFile from "../../data/parliament-current.json";
import cantonalParliamentsFile from "../../data/cantonal-parliaments.json";
import cantonalGovernmentsFile from "../../data/cantonal-governments.json";
import mediaFile from "../../data/media.json";
import campaignFinancingFile from "../../data/campaign-financing.json";
import type {
  Ballot,
  BallotFile,
  CampaignFinancing,
  CampaignFinancingFile,
  CantonalGovernment,
  CantonalGovernmentsFile,
  CantonalParliaments,
  CantonalParliamentsFile,
  LinkEntry,
  MediaFile,
  MediaOwnership,
  Parliament,
  ParliamentFile,
  PartiesFile,
  Party,
  StateSite,
  StateSitesFile,
  TerritoriesFile,
  Territory,
  Tool,
  ToolsFile,
} from "../types.ts";

/** An entry whose URL is known. */
export type Linked<T extends LinkEntry> = T & { url: string };

/** The JSON types inferred by TypeScript are too loose (plain strings); `npm run check` guarantees the shapes of src/types.ts. */
function checked<T>(json: unknown): T {
  return json as T;
}
const territories: Territory[] = checked<TerritoriesFile>(territoriesFile).territories;
const parties: Party[] = checked<PartiesFile>(partiesFile).parties;
const stateSites: StateSite[] = checked<StateSitesFile>(stateSitesFile).state_sites;
const allTools: Tool[] = checked<ToolsFile>(toolsFile).tools;

export const ballot: Ballot = checked<BallotFile>(ballotFile).ballot;


/** Current federal composition, from data/parliament-current.json (generated by `npm run parliament`). */
export const parliament: Parliament = checked<ParliamentFile>(parliamentFile).parliament;

/** Seats per party at the latest election of each covered canton's parliament, from data/cantonal-parliaments.json (generated by `npm run cantonal-parliaments`). */
export const cantonalParliaments: CantonalParliaments = checked<CantonalParliamentsFile>(cantonalParliamentsFile).cantonal_parliaments;

/** Cantonal governments kept by hand, each member with its sources and check date (data/cantonal-governments.json). */
export const cantonalGovernments: CantonalGovernment[] = checked<CantonalGovernmentsFile>(cantonalGovernmentsFile).cantonal_governments;

/** The media, their publishers and owners, and the fög values, kept by hand (data/media.json, PRD-0001 US-20 to US-25). Removal fingerprints are left out of the bundle. */
export const mediaOwnership: MediaOwnership = checked<MediaFile>(mediaFile).media_ownership;

/** Campaign budgets and donations of each ballot item, from data/campaign-financing.json (generated by `npm run campaign-financing`). */
export const campaignFinancing: CampaignFinancing = checked<CampaignFinancingFile>(campaignFinancingFile).campaign_financing;

/** A verified entry always has a URL (`npm run check` enforces: url null exactly when not_found). */
function isVerified<T extends LinkEntry>(x: T): x is Linked<T> {
  return x.status === "verified" && x.url !== null;
}

/** Parties of a territory; an unverified party URL is hidden. */
function partiesOf(code: string): Party[] {
  return parties.filter((p) => p.territory === code).map((p) => (isVerified(p) ? p : { ...p, url: null }));
}
/** Verified official sites of a territory, the canton's own site first. */
function stateSitesOf(code: string): Linked<StateSite>[] {
  return stateSites.filter((s) => s.territory === code).filter(isVerified);
}

export interface Level {
  parties: Party[];
  stateSites: Linked<StateSite>[];
}
export interface Canton extends Level {
  name: string;
  /** The canton's own name for its parliament ("Grand Conseil", "Parlement"); `npm run check` requires it for a covered canton. */
  parliament: string;
  note: string;
}

/** The 26 cantons, covered or not, as [code, name]. */
export const allCantons: [string, string][] = territories.filter((t) => t.code !== "CH").map((t) => [t.code, t.name]);

export const federal: Level = { parties: partiesOf("CH"), stateSites: stateSitesOf("CH") };

/** Covered cantons: those with at least one party in data/parties.json. */
export const cantons: Record<string, Canton> = {};
for (const t of territories) {
  if (t.code === "CH" || !partiesOf(t.code).length) continue;
  cantons[t.code] = { name: t.name, parliament: t.parliament || "", note: t.note || "", parties: partiesOf(t.code), stateSites: stateSitesOf(t.code) };
}

/** Verified decision aids, in the order of data/tools.json. */
export const tools: Linked<Tool>[] = allTools.filter(isVerified);

function urlOf(entries: LinkEntry[], file: string, id: string): string {
  const entry = entries.find((x) => x.id === id);
  if (!entry || !isVerified(entry)) throw new Error(`${file} : pas de lien vérifié pour « ${id} »`);
  return entry.url;
}
export function stateSiteUrl(id: string): string {
  return urlOf(stateSites, "data/state-sites.json", id);
}
export function toolUrl(id: string): string {
  return urlOf(allTools, "data/tools.json", id);
}
